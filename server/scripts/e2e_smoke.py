"""端到端冒烟测试：以用户视角走完 识别 -> 版本 -> 生成方案 -> 反馈 -> 统计。

用法（在 server 目录下，需先启动服务）：
    .venv\\Scripts\\python.exe scripts\\e2e_smoke.py [base_url]
"""
from __future__ import annotations

import json
import sys
import urllib.request

BASE = sys.argv[1] if len(sys.argv) > 1 else "http://127.0.0.1:8017"
FAILS: list[str] = []


def call(method: str, path: str, body: dict | None = None):
    data = json.dumps(body, ensure_ascii=False).encode("utf-8") if body is not None else None
    req = urllib.request.Request(BASE + path, data=data, method=method,
                                 headers={"Content-Type": "application/json; charset=utf-8"})
    try:
        with urllib.request.urlopen(req, timeout=120) as resp:
            return resp.status, json.loads(resp.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        return e.code, json.loads(e.read().decode("utf-8") or "{}")


def check(label: str, cond: bool, extra: str = "") -> None:
    print(("PASS " if cond else "FAIL ") + label + (f"  <- {extra}" if not cond and extra else ""))
    if not cond:
        FAILS.append(label)


print("== health ==")
st, h = call("GET", "/api/health")
check("health ok", st == 200 and h.get("ok") is True, str(h))

print("\n== identify ==")
for text, want in [("帮我搞 Node", "Node.js"), ("我想装MySQL", "MySQL"),
                   ("要不要装 Docker", "Docker"), ("我想装个 VSCode", "VS Code")]:
    st, r = call("POST", "/api/identify", {"text": text})
    got = (r.get("software") or {}).get("display_name")
    check(f"identify {text!r} -> {want}", st == 200 and got == want, f"got={got} raw={r}")
    if st == 200:
        pass

print("\n== catalog ==")
st, catalog = call("GET", "/api/software")
items = catalog.get("items") if isinstance(catalog, dict) else catalog
check("catalog >= 20", st == 200 and isinstance(items, list) and len(items) >= 20,
      f"count={len(items) if isinstance(items, list) else catalog}")

print("\n== versions ==")
st, r = call("POST", "/api/identify", {"text": "nodejs"})
sw_id = (r.get("software") or {}).get("id")
st, vs = call("GET", f"/api/software/{sw_id}/versions?platform=windows")
vlist = vs.get("versions") if isinstance(vs, dict) else vs
check("versions non-empty", st == 200 and isinstance(vlist, list) and len(vlist) > 0,
      f"st={st} body={str(vs)[:200]}")
ver = vlist[0]["version"] if isinstance(vlist, list) and vlist else None
check("latest flagged first", bool(vlist) and vlist[0].get("is_latest") is True, str(vlist[:1]))

print("\n== plan ==")
plan_body = {"software": "nodejs", "display_name": "Node.js", "version": ver, "platform": "windows"}
st, plan = call("POST", "/api/plans", plan_body)
check("plan generated", st == 200 and bool(plan.get("markdown")), f"st={st} body={str(plan)[:300]}")
if plan.get("markdown"):
    md = plan["markdown"]
    check("plan has install section", "安装" in md or "install" in md.lower())
    check("plan mode set", plan.get("install_mode") in {"script", "official-link"},
          str(plan.get("install_mode")))
    if plan.get("install_mode") == "script":
        check("plan has script", bool((plan.get("script") or "").strip()), "empty script")
    st2, plan2 = call("POST", "/api/plans", plan_body)
    check("plan cached (same id)", st2 == 200 and plan2.get("id") == plan.get("id"),
          f"{plan2.get('id')} != {plan.get('id')}")
    st3, detail = call("GET", f"/api/plans/{plan['id']}")
    check("plan detail", st3 == 200 and detail.get("markdown") == md)

    # 内容红线：方案只讲安装，不夹带学习资源 / 软件介绍
    banned = ["学习资源", "推荐教程", "入门教程", "官方文档推荐", "B站", "bilibili",
              "视频教程", "学习路线"]
    hit = [w for w in banned if w in md]
    check("no study-resource padding", not hit, f"命中: {hit}")
    checker = plan.get("model")
    check("plan records generator (ai model or fallback None)", checker is None or isinstance(checker, str),
          f"model={checker!r}")
    gen = f"AI · {checker}" if checker else "本地兜底模板"
    print(f"     (生成方式: {gen})")
    # 服务端已配置 AI 时，新生成的方案必须来自 AI —— 否则说明调用静默失败被兜底了
    if h.get("ai_configured"):
        check("plan actually generated by AI", checker is not None, f"model={checker!r}，AI 已配置却走了兜底")

    if plan.get("install_mode") == "script":
        script = plan.get("script") or ""
        check("script has chinese comments", any("\u4e00" <= c <= "\u9fff" for c in script))
        has_verify = any(k in script for k in ("--version", "-version", "version",
                                               "验证", "which ", "Get-Command",
                                               "echo $", "Write-Host"))
        check("script has verification step", has_verify, "未发现版本/验证命令")
        if plan.get("platform") == "windows":
            check("windows script is powershell", plan.get("script_type") == "powershell",
                  str(plan.get("script_type")))
        else:
            check("non-windows script is bash", plan.get("script_type") == "bash",
                  str(plan.get("script_type")))

    print("\n== feedback ==")
    st, fb = call("POST", "/api/feedback",
                  {"plan_id": plan["id"], "rating": "valid", "content": "脚本能跑通，感谢！"})
    check("feedback accepted", st in (200, 201), f"st={st} body={fb}")

print("\n== macos plan ==")
st, vs_mac = call("GET", f"/api/software/{sw_id}/versions?platform=macos")
vmac = vs_mac.get("versions") if isinstance(vs_mac, dict) else vs_mac
mac_ver = vmac[0]["version"] if vmac else ver
st, mac_plan = call("POST", "/api/plans", {"software": "nodejs", "display_name": "Node.js",
                                           "version": mac_ver, "platform": "macos"})
check("macos plan generated", st == 200 and bool(mac_plan.get("markdown")),
      f"st={st} body={str(mac_plan)[:200]}")
if mac_plan.get("install_mode") == "script":
    check("macos script is bash", mac_plan.get("script_type") == "bash", str(mac_plan.get("script_type")))
    mac_script = mac_plan.get("script") or ""
    check("macos script has shebang", mac_script.lstrip().startswith("#!"), mac_script[:40])
    # 允许 brew / nvm / 官方二进制直装三种合理路线
    installable = any(k in mac_script for k in (
        "brew", "nvm", "curl", "wget", "tar ", "pkg", "install", "PKG_MANAGER"))
    check("macos script installs something", installable, mac_script[:120])

print("\n== official-link plan (VS Code) ==")
st, vsc = call("POST", "/api/identify", {"text": "vscode"})
vsc_id = (vsc.get("software") or {}).get("id")
st, vsc_vs = call("GET", f"/api/software/{vsc_id}/versions?platform=windows")
vsc_list = vsc_vs.get("versions") if isinstance(vsc_vs, dict) else vsc_vs
vsc_ver = vsc_list[0]["version"] if vsc_list else None
st, vsc_plan = call("POST", "/api/plans", {"software": "vscode", "display_name": "VS Code",
                                           "version": vsc_ver, "platform": "windows"})
check("vscode plan is official-link", st == 200 and vsc_plan.get("install_mode") == "official-link",
      f"mode={vsc_plan.get('install_mode')}")
check("vscode plan has download url", "https://" in (vsc_plan.get("markdown") or ""))
check("vscode plan has no script", not (vsc_plan.get("script") or "").strip())

print("\n== stats ==")

st, s = call("POST", "/api/stats", {"kind": "install_run", "key": "Node.js", "software_name": "Node.js"})
check("stats ok", st == 200 and s.get("ok") is True, f"st={st} body={s}")

print("\n结果:", "全部通过 🎉" if not FAILS else f"{len(FAILS)} 项失败: {FAILS}")
sys.exit(1 if FAILS else 0)
